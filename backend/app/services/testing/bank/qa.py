    scope = rng.choice(["function", "module", "session"])
    m1, m2 = rng.randint(2, 5), rng.randint(2, 5)
    ans = {"function": m1 + m2, "module": 2, "session": 1}[scope]
    return Rendered(f"Фикстура `db` объявлена в conftest.py с `scope='{scope}'`. Её используют {m1} тестов в test_a.py и {m2} "
                    "тестов в test_b.py. Сколько раз выполнится код установки фикстуры за прогон?", "numeric", ans,
                    code=f"@pytest.fixture(scope='{scope}')\ndef db():\n    conn = connect()\n    yield conn\n    conn.close()",
                    code_lang="python")


