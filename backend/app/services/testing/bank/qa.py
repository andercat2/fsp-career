@family("qa.branch_coverage", T, 3, "numeric", "Покрытие ветвей", time_limit=150)
def qa_branch_coverage(rng: random.Random, _l):
    k = rng.randint(3, 5)
    lines = ["def tariff(x):"]
    for i in range(k - 1):
        kw = "if" if i == 0 else "elif"
        lines.append(f"    {kw} x < {10 * (i + 1)}:\n        r = {i + 1}")
    lines.append(f"    else:\n        r = {k}")
    tail = rng.random() < 0.5
    if tail:
        lines.append("    if x % 2 == 0:\n        r *= 2")
    lines.append("    return r")
    return Rendered("Какое минимальное число тестов даст 100% покрытие ветвей (branch coverage) этой функции?", "numeric",
                    k, code="\n".join(lines), code_lang="python",
                    explanation="Каждую ветку цепочки if/elif/else нужно пройти хотя бы раз; независимое условие "
                                "можно покрыть теми же тестами.")


@family("qa.cyclomatic", T, 4, "numeric", "Цикломатическая сложность", time_limit=150)
def qa_cyclomatic(rng: random.Random, _l):
    n_if, n_loop = rng.randint(1, 3), rng.randint(0, 2)
    body = []
    for i in range(n_loop):
        body.append(f"    for item in batch_{i}:\n        total += item")
    for i in range(n_if):
        body.append(f"    if total > {100 * (i + 1)}:\n        total -= {i + 1}")
    rng.shuffle(body)
    code = "def process(batch_0, batch_1, total=0):\n" + "\n".join(body) + "\n    return total"
    return Rendered("Чему равна цикломатическая сложность функции (без учёта составных логических условий)?", "numeric",
                    n_if + n_loop + 1, code=code, code_lang="python", explanation="V(G) = число точек ветвления + 1.")


