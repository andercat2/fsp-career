@family("qa.equivalence", T, 2, "numeric", "Классы эквивалентности", time_limit=120)
def qa_equivalence(rng: random.Random, _l):
    k = rng.randint(2, 4)
    lo = rng.choice([0, 1, 18])
    cuts = sorted(rng.sample(range(lo + 2, lo + 60), k - 1))
    bounds = [lo, *cuts]
    hi = cuts[-1] + rng.randint(10, 40)
    ranges = [f"[{bounds[i]}; {bounds[i + 1] - 1}]" for i in range(k - 1)] + [f"[{bounds[-1]}; {hi}]"]
    return Rendered(f"Поле принимает целые числа от {lo} до {hi}. Внутри диапазона разные тарифы для интервалов: "
                    f"{', '.join(ranges)}. Сколько классов эквивалентности по значению нужно выделить, включая "
                    "невалидные значения ниже и выше допустимого диапазона?", "numeric", k + 2)


